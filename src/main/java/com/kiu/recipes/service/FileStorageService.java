package com.kiu.recipes.service;

import com.kiu.recipes.exception.FileStorageException;
import com.kiu.recipes.exception.InvalidFileException;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.util.UUID;

/**
 * Stores uploaded images on the local disk. The stored name is generated by the server
 * (UUID + extension derived from the file's magic bytes); the client-supplied file name
 * and content type are never trusted.
 */
@Service
public class FileStorageService {

    private static final Logger log = LoggerFactory.getLogger(FileStorageService.class);

    private final Path root;

    public FileStorageService(@Value("${app.upload-dir}") String uploadDir) {
        this.root = Paths.get(uploadDir).toAbsolutePath().normalize();
        try {
            Files.createDirectories(root);
        } catch (IOException e) {
            throw new FileStorageException("Could not create upload directory " + root, e);
        }
    }

    public Path getRoot() {
        return root;
    }

    /** Validates and saves the image; returns the generated file name to persist in the database. */
    public String store(MultipartFile file) {
        if (file == null || file.isEmpty()) {
            throw new InvalidFileException("No file was uploaded (the 'file' part is missing or empty)");
        }
        try (InputStream in = file.getInputStream()) {
            byte[] header = in.readNBytes(12);
            String extension = detectImageExtension(header);
            if (extension == null) {
                throw new InvalidFileException("Only JPEG, PNG, GIF and WEBP images are accepted");
            }
            String storedName = UUID.randomUUID() + "." + extension;
            // header bytes were consumed from this stream, so re-open to copy the whole file
            try (InputStream full = file.getInputStream()) {
                Files.copy(full, root.resolve(storedName), StandardCopyOption.REPLACE_EXISTING);
            }
            return storedName;
        } catch (IOException e) {
            throw new FileStorageException("Failed to store uploaded file", e);
        }
    }

    /** Best-effort delete; never throws. Ignores names that would escape the upload directory. */
    public void delete(String storedName) {
        if (storedName == null || storedName.isBlank()) {
            return;
        }
        Path target = root.resolve(storedName).normalize();
        if (!target.startsWith(root)) {
            log.warn("Refusing to delete path outside upload dir: {}", storedName);
            return;
        }
        try {
            Files.deleteIfExists(target);
        } catch (IOException e) {
            log.warn("Could not delete file {}", target, e);
        }
    }

    static String detectImageExtension(byte[] h) {
        if (h.length >= 3 && (h[0] & 0xFF) == 0xFF && (h[1] & 0xFF) == 0xD8 && (h[2] & 0xFF) == 0xFF) {
            return "jpg";
        }
        if (h.length >= 8 && (h[0] & 0xFF) == 0x89 && h[1] == 'P' && h[2] == 'N' && h[3] == 'G'
                && h[4] == 0x0D && h[5] == 0x0A && h[6] == 0x1A && h[7] == 0x0A) {
            return "png";
        }
        if (h.length >= 6 && h[0] == 'G' && h[1] == 'I' && h[2] == 'F' && h[3] == '8'
                && (h[4] == '7' || h[4] == '9') && h[5] == 'a') {
            return "gif";
        }
        if (h.length >= 12 && h[0] == 'R' && h[1] == 'I' && h[2] == 'F' && h[3] == 'F'
                && h[8] == 'W' && h[9] == 'E' && h[10] == 'B' && h[11] == 'P') {
            return "webp";
        }
        return null;
    }
}
